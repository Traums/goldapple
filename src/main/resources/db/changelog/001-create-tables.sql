CREATE TABLE customers
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name  VARCHAR(100) NOT NULL,
    phone      VARCHAR(20)  NOT NULL,
    status     VARCHAR(32)  NOT NULL,
    created_at TIMESTAMP    NOT NULL,
    CONSTRAINT chk_customers_status CHECK (status IN ('ACTIVE', 'BLOCKED'))
);

CREATE TABLE products
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku            VARCHAR(32)    NOT NULL,
    name           VARCHAR(200)   NOT NULL,
    brand          VARCHAR(100)   NOT NULL,
    category       VARCHAR(32)    NOT NULL,
    price          NUMERIC(15, 2) NOT NULL,
    stock_quantity INTEGER        NOT NULL,
    status         VARCHAR(32)    NOT NULL,
    created_at     TIMESTAMP      NOT NULL,
    CONSTRAINT uq_products_sku UNIQUE (sku),
    CONSTRAINT chk_products_category CHECK (category IN ('SKINCARE', 'MAKEUP', 'HAIRCARE', 'FRAGRANCE')),
    CONSTRAINT chk_products_status CHECK (status IN ('ACTIVE', 'OUT_OF_STOCK', 'ARCHIVED')),
    CONSTRAINT chk_products_price CHECK (price >= 0),
    CONSTRAINT chk_products_stock CHECK (stock_quantity >= 0)
);

CREATE TABLE orders
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  BIGINT         NOT NULL,
    status       VARCHAR(32)    NOT NULL,
    total_amount NUMERIC(15, 2) NOT NULL,
    created_at   TIMESTAMP      NOT NULL,
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
    CONSTRAINT chk_orders_status CHECK (status IN ('NEW', 'PAID', 'CANCELLED', 'COMPLETED')),
    CONSTRAINT chk_orders_total CHECK (total_amount >= 0)
);

CREATE INDEX idx_orders_customer_id ON orders (customer_id);

CREATE TABLE order_items
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL,
    product_id BIGINT         NOT NULL,
    quantity   INTEGER        NOT NULL,
    price      NUMERIC(15, 2) NOT NULL,
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT uq_order_items_order_product UNIQUE (order_id, product_id),
    CONSTRAINT chk_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT chk_order_items_price CHECK (price >= 0)
);

CREATE INDEX idx_order_items_product_id ON order_items (product_id);
